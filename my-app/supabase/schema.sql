-- Sajha Pahal — Supabase schema
--
-- No reports schema existed before this migration: the app shipped with
-- hardcoded seed data in lib/reports.js and only the `profiles` table existed.
-- Run this once in the Supabase SQL editor (or with the CLI) to enable real
-- report storage. The frontend is already wired to these objects.
--
--   Dashboard -> SQL Editor -> paste -> Run
--
-- Nothing here requires PostGIS: locations use plain DOUBLE PRECISION
-- latitude/longitude columns (WGS84), which is what Leaflet consumes directly.

-- ---------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------
-- Enums so ordering works: `order by severity desc` puts critical first.
create type public.report_severity as enum ('low', 'medium', 'high', 'critical');
create type public.report_status as enum ('pending', 'in_progress', 'resolved');

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------
create table public.reports (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Reporter is nullable so civic records survive account deletion.
  user_id uuid references auth.users (id) on delete set null,
  reporter_name text not null default 'Anonymous',
  title text not null check (char_length(trim(title)) between 3 and 140),
  description text not null default '',
  category text not null,
  severity public.report_severity not null default 'medium',
  status public.report_status not null default 'pending',
  location_name text not null default '',
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  image_url text
);

create index reports_created_at_idx on public.reports (created_at desc);
create index reports_status_idx on public.reports (status);
create index reports_category_idx on public.reports (category);

-- Progress timeline shown on the report details page. The first row is written
-- by the client at submit time.
create table public.report_status_history (
  id bigint generated by default as identity primary key,
  report_id uuid not null references public.reports (id) on delete cascade,
  status public.report_status not null,
  note text,
  created_at timestamptz not null default now()
);

create index report_status_history_report_idx
  on public.report_status_history (report_id, created_at);

-- One row per citizen verification. The primary key stops double-voting.
create table public.report_verifications (
  report_id uuid not null references public.reports (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (report_id, user_id)
);

-- ---------------------------------------------------------------------------
-- Views (security_invoker so RLS on the base table still applies)
-- ---------------------------------------------------------------------------
create or replace view public.report_category_counts
  with (security_invoker = true) as
  select category, count(*)::int as count
  from public.reports
  group by category
  order by count desc;

-- ---------------------------------------------------------------------------
-- updated_at trigger
-- ---------------------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger reports_touch_updated_at
  before update on public.reports
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
-- Reports are civic records: anyone may read them, only signed-in users may
-- create them, and only the reporter may edit their own.
alter table public.reports enable row level security;
alter table public.report_status_history enable row level security;
alter table public.report_verifications enable row level security;

create policy "Reports are publicly readable"
  on public.reports for select
  to anon, authenticated
  using (true);

create policy "Signed-in users can create reports"
  on public.reports for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "Reporters can update their own reports"
  on public.reports for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Reporters can delete their own reports"
  on public.reports for delete
  to authenticated
  using (auth.uid() = user_id);

create policy "Status history is publicly readable"
  on public.report_status_history for select
  to anon, authenticated
  using (true);

create policy "Reporters can add history to their own reports"
  on public.report_status_history for insert
  to authenticated
  with check (
    exists (
      select 1 from public.reports r
      where r.id = report_id and r.user_id = auth.uid()
    )
  );

create policy "Verifications are publicly readable"
  on public.report_verifications for select
  to anon, authenticated
  using (true);

create policy "Signed-in users can verify a report"
  on public.report_verifications for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "Users can remove their own verification"
  on public.report_verifications for delete
  to authenticated
  using (auth.uid() = user_id);

-- Explicit grants; new Supabase projects grant these by default, but the
-- existing `profiles` table was missing them, so be explicit.
grant usage on schema public to anon, authenticated;
grant select on public.reports to anon, authenticated;
grant insert, update, delete on public.reports to authenticated;
grant select on public.report_status_history to anon, authenticated;
grant insert on public.report_status_history to authenticated;
grant select on public.report_verifications to anon, authenticated;
grant insert, delete on public.report_verifications to authenticated;
grant select on public.report_category_counts to anon, authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- ---------------------------------------------------------------------------
-- Storage: report images
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('report-images', 'report-images', true)
on conflict (id) do nothing;

create policy "Report images are publicly readable"
  on storage.objects for select
  using (bucket_id = 'report-images');

create policy "Signed-in users can upload report images"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'report-images');

create policy "Uploaders can replace their own report images"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'report-images' and owner = auth.uid());

create policy "Uploaders can delete their own report images"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'report-images' and owner = auth.uid());
